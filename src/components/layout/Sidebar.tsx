function NavLink({
  href,
  label,
  icon,
  active,
  collapsed,
  onClick,
  badge = 0,
}: {
  href: string;
  label: string;
  icon: React.ReactNode;
  active: boolean;
  collapsed: boolean;
  onClick: () => void;
  badge?: number;
}) {
  return (
    <Link
      href={href}
      onClick={onClick}
      className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
        active
          ? "bg-red-600/15 text-red-400"
          : "text-charcoal-400 hover:bg-charcoal-800/50 hover:text-charcoal-200"
      }`}
      title={collapsed ? label : undefined}
    >
      <span className={`relative ${active ? "text-red-400" : "text-charcoal-500"}`}>
        {icon}
        {badge > 0 && collapsed && (
          <span className="absolute -right-1 -top-1 h-2 w-2 rounded-full bg-red-500" />
        )}
      </span>
      <span className={`flex-1 ${collapsed ? "hidden" : ""}`}>{label}</span>
      {!collapsed && badge > 0 && (
        <span className="rounded-full bg-red-600 px-1.5 py-0.5 text-[10px] font-bold text-white">
          {badge > 99 ? "99+" : badge}
        </span>
      )}
    </Link>
  );
}

export function Sidebar({
  username,
  unreadMessages = 0,
}: {
  username: string;
  unreadMessages?: number;
}) {
  const pathname = usePathname();
  const [collapsed, setCollapsed] = useState(false);
  const { isOpen, close } = useMobileMenu();

  const navContent = (
    <>
      {/* Logo */}
      <div className="flex h-12 items-center border-b border-charcoal-800/40 px-4">
        <span className={`text-sm font-semibold tracking-tight text-charcoal-100 ${collapsed ? "hidden" : "md:block"}`}>
          Orbit42
        </span>
        {collapsed && (
          <span className="text-sm font-semibold tracking-tight text-charcoal-100">
            42
          </span>
        )}
      </div>

      {/* Nav */}
      <nav className="flex-1 space-y-1 px-2 py-3">
        {/* Social — what other people are doing */}
        <NavLink
          href="/feed"
          label="Feed"
          icon={icons.home}
          active={pathname === "/feed"}
          collapsed={collapsed}
          onClick={close}
        />
        <NavLink
          href="/explore"
          label="Explore"
          icon={icons.users}
          active={pathname === "/explore"}
          collapsed={collapsed}
          onClick={close}
        />
        <NavLink
          href={`/${username}`}
          label="My profile"
          icon={icons.user}
          active={pathname === `/${username}`}
          collapsed={collapsed}
          onClick={close}
        />
        <NavLink
          href="/messages"
          label="Messages"
          icon={icons.chat}
          active={pathname === "/messages" || pathname.startsWith("/messages/")}
          collapsed={collapsed}
          onClick={close}
          badge={unreadMessages}
        />

        <div className="my-3 border-t border-charcoal-800/40" />
        {!collapsed && (
          <p className="px-3 pb-1 text-[10px] font-semibold uppercase tracking-wider text-charcoal-500">
            Manage
          </p>
        )}

        {NAV_ITEMS.map((item) => {
          const href = `/${username}${item.href}`;
          const isActive =
            pathname === href || pathname.startsWith(href + "/");
          return (
            <NavLink
              key={item.label}
              href={href}
              label={item.label}
              icon={icons[item.icon]}
              active={isActive}
              collapsed={collapsed}
              onClick={close}
            />
          );
        })}
      </nav>

      {/* Bottom: Collapse (desktop only) */}
      <div className="hidden border-t border-charcoal-800/40 p-2 md:block">
        <button
          onClick={() => setCollapsed(!collapsed)}
          className="flex w-full items-center gap-3 rounded-lg px-3 py-2 text-sm text-charcoal-500 hover:bg-charcoal-800/50 hover:text-charcoal-300"
        >
          <svg className={`h-5 w-5 transition-transform ${collapsed ? "rotate-180" : ""}`} fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" d="M18.75 19.5l-7.5-7.5 7.5-7.5m-6 15L5.25 12l7.5-7.5" />
          </svg>
          {!collapsed && "Collapse"}
        </button>
      </div>
    </>
  );

  return (
    <>
      {/* Desktop sidebar */}
      <aside
        className={`hidden h-screen flex-col border-r border-charcoal-800/40 bg-[rgb(var(--bg-surface))] transition-all md:flex ${
          collapsed ? "w-16" : "w-56"
        }`}
      >
        {navContent}
      </aside>

      {/* Mobile overlay */}
      {isOpen && (
        <>
          <div
            className="fixed inset-0 z-40 bg-black/60 backdrop-blur-sm md:hidden"
            onClick={close}
          />
          <aside className="fixed inset-y-0 left-0 z-50 flex w-64 flex-col bg-[rgb(var(--bg-surface))] shadow-2xl md:hidden">
            {navContent}
          </aside>
        </>
      )}
    </>
  );
}
